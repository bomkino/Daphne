#!/usr/bin/env node
// Writes prototype/story/marks.js: the geometry the story page draws with, taken from
// the brand's own mark code (brand/tools/mark.mjs), so the leaves and the logo on
// pitch.dog/daphne/story/ are the brand's, never a copy drawn by hand.
//
//   node tools/story-marks.mjs
//
// Run it again after any change to brand/tools/mark.mjs, and commit marks.js.
import { writeFileSync } from 'node:fs'
import { leafBracket, lockup, HERO_LEAF, f } from '../brand/tools/mark.mjs'

// The story's leaf: a single bay leaf pointing up, base at 0,0 (the brand book's story leaf).
const SL = leafBracket({ side: 1, x0: 0, yTop: -500, yBot: 0, sag: 26, W: 150, stalk: 0.1, stalkCurl: 0.4, slit: 0.07, wave: 0.03 })
// The hero logo, (Daphne), with veined leaves.
const HK = lockup({ leaf: HERO_LEAF })
// Its letters, one path each, so the name can rise a letter at a time.
const LETTERS = [...HK.word.matchAll(/<path transform="translate\(([-\d.]+) 0\)" d="([^"]+)"\/>/g)].map((m) => [+m[1], m[2]])
const pt = (p) => p.map((n) => +f(n))

const marks = {
  LEAF: SL.d, STALK: SL.stalk, LEN: 500,
  LETTERS,
  BL: HK.L.d, BLS: HK.L.stalk, BR: HK.R.d, BRS: HK.R.stalk,
  NB: HK.box.map((n) => +f(n)), A0: pt(HK.L.P(0)), A1: pt(HK.L.P(1)), Z0: pt(HK.R.P(0)),
}

const out = new URL('../prototype/story/marks.js', import.meta.url)
writeFileSync(out, `// Generated by tools/story-marks.mjs from brand/tools/mark.mjs. Don't edit by hand.\n// Public domain (CC0), like the rest of Daphne's brand.\nexport default ${JSON.stringify(marks)};\n`)
console.log('wrote prototype/story/marks.js')
